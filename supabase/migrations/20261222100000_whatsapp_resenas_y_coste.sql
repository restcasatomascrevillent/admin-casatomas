-- ─── 3. Cuándo toca pedir la reseña ─────────────────────────────────────────
-- Misma regla que momentoResena() (resenas.ts): hora + 3 h; después de las
-- 22:00 (o pasada la medianoche), al día siguiente a las 12:00; antes de las
-- 10:00, a las 10:00.
create or replace function public.whatsapp_resena_momento(p_fecha date, p_hora time)
returns timestamptz
language sql
stable
set search_path = public, pg_temp
as $$
  select case
    when extract(epoch from p_hora) / 60 + 180 > 22 * 60
      then ((p_fecha + 1) + time '12:00') at time zone 'Europe/Madrid'
    when extract(epoch from p_hora) / 60 + 180 < 10 * 60
      then (p_fecha + time '10:00') at time zone 'Europe/Madrid'
    else (p_fecha + p_hora + interval '3 hours') at time zone 'Europe/Madrid'
  end;
$$;
comment on function public.whatsapp_resena_momento(date, time) is
  'Instante en que se pide la reseña por WhatsApp de una reserva (fecha y hora de Madrid): hora + 3 h, sin escribir después de las 22:00 (pasa al día siguiente a las 12:00). Igual que momentoResena() de whatsapp-reservas/resenas.ts.';

-- ¿Hay alguna reserva a la que ya le toca y aún no se ha mirado? (ventana de 12 h, como REGLAS_RESENA)
create or replace function public.whatsapp_resenas_hay_trabajo()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
      from public.reservas r
     where r.fecha between (now() at time zone 'Europe/Madrid')::date - 2 and (now() at time zone 'Europe/Madrid')::date
       and r.estado in ('confirmada', 'completada')
       and coalesce(r.telefono, '') <> ''
       and public.whatsapp_resena_momento(r.fecha, r.hora) <= now()
       and public.whatsapp_resena_momento(r.fecha, r.hora) > now() - interval '12 hours'
       and not exists (select 1 from public.whatsapp_resenas w where w.reserva_id = r.id)
  );
$$;

create or replace function public.whatsapp_resenas_disparar()
returns boolean
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_url text;
  v_secreto text;
begin
  select decrypted_secret into v_url from vault.decrypted_secrets where name = 'project_url' limit 1;
  select decrypted_secret into v_secreto from vault.decrypted_secrets where name = 'whatsapp_resenas_cron_secret' limit 1;
  -- Sin secreto (WhatsApp sin activar en este entorno): no se llama a nada.
  if coalesce(v_url, '') = '' or coalesce(v_secreto, '') = '' then
    return false;
  end if;
  if not public.whatsapp_resenas_hay_trabajo() then
    return false;
  end if;
  perform net.http_post(
    url := rtrim(v_url, '/') || '/functions/v1/whatsapp-reservas/resenas',
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-webhook-secret', v_secreto),
    body := '{"origen":"cron"}'::jsonb,
    timeout_milliseconds := 60000);
  return true;
end;
$$;

revoke all on function public.whatsapp_resena_momento(date, time) from public, anon, authenticated;
revoke all on function public.whatsapp_resenas_hay_trabajo() from public, anon, authenticated;
revoke all on function public.whatsapp_resenas_disparar() from public, anon, authenticated;
grant execute on function public.whatsapp_resena_momento(date, time) to service_role;
grant execute on function public.whatsapp_resenas_hay_trabajo() to service_role;
grant execute on function public.whatsapp_resenas_disparar() to service_role;

-- ─── 4. pg_cron cada 10 minutos ─────────────────────────────────────────────
do $$
begin
  if exists (select 1 from pg_namespace where nspname = 'cron') then
    perform cron.unschedule('whatsapp-resenas') where exists (select 1 from cron.job where jobname = 'whatsapp-resenas');
    perform cron.schedule('whatsapp-resenas', '7-59/10 * * * *', 'select public.whatsapp_resenas_disparar();');
  end if;
end;
$$;

